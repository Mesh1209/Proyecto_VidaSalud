    private void btnActualizarPacienteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarPacienteActionPerformed
        // TODO add your handling code here:
        try {
            // 1. Validar que exista un ID seleccionado para editar
            if (txtIdPaciente.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Primero debe buscar o seleccionar un paciente para actualizar.", "Advertencia", JOptionPane.WARNING_MESSAGE);
                return;
            }

            int idPaciente = Integer.parseInt(txtIdPaciente.getText().trim());
            LocalDate fechaNacimiento = txtFechaNacimiento.getDate();
            String tipoDoc = obtenerTextoDelGrupo(btnGroupDoc);
            String genero = obtenerTextoDelGrupo(btnGroupGenero);
            // 2. Llamar al controlador para actualizar
            boolean exito = controladorPaciente.actualizarPaciente(
                idPaciente,
                txtNombrePaciente.getText().trim(),
                txtApellidoPaciente.getText().trim(),
                tipoDoc,
                txtDNI.getText().trim(),
                fechaNacimiento,
                genero,
                txtTelefono.getText().trim(),
                txtEmail.getText().trim(),
                txtDireccion.getText().trim()
            );

            // 3. Mostrar respuesta y limpiar
            if (exito) {
                JOptionPane.showMessageDialog(this, "Datos del paciente actualizados correctamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                LimpiarPaciente();
            } else {
                JOptionPane.showMessageDialog(this, "No se pudo actualizar la información del paciente.", "Error", JOptionPane.ERROR_MESSAGE);
            }

        } catch (DateTimeParseException e) {
            JOptionPane.showMessageDialog(this, "Formato de fecha inválido. Use el formato dd/MM/yyyy.", "Error de Fecha", JOptionPane.ERROR_MESSAGE);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El ID del paciente no es válido.", "Error", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Ocurrió un error inesperado: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnActualizarPacienteActionPerformed
    
