    private void cargarDatosTabla(List<ListaHorarioCita> listaHorarioCitas) {
        // 1. Limpiamos la tabla siempre al inicio
        modelo.setRowCount(0);
        DateTimeFormatter formatter = DateTimeFormatter.ofPattern("dd/MM/yyyy HH:mm");
        // 2. Verificar si la lista que llegó está vacía o es nula
        if (listaHorarioCitas == null || listaHorarioCitas.isEmpty()) {
            System.out.println("No hay horarios para mostrar con los criterios actuales");
            return;
        }

        // 3. Tu mismo bucle (se mantiene intacto, solo cambia la variable a listaHorarios)
        for (ListaHorarioCita h : listaHorarioCitas) {
            modelo.addRow(new Object[]{
                h.getId_medico(),
                h.getNombre(), 
                h.getApellido(), 
                h.getEspecialidad(),
                h.getDia_semana(), 
                h.getHora_inicio().format(formatter), 
                h.getHora_fin().format(formatter)
            });
        }
        
    }

