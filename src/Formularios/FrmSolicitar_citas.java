    private void btnRegistarCitaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistarCitaActionPerformed
        DateTimeFormatter formateador = DateTimeFormatter.ofPattern("dd/MM/yyyy HH:mm");
        int filaSeleccionada = TablaHorarioCita.getSelectedRow();
        if (filaSeleccionada == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, seleccione una fila de la tabla.");
            return; // Salimos del método para que no continúe
        }
        
        try {
            int idPaciente = Integer.parseInt(txtIdPaciente.getText());
            int idMedico = Integer.parseInt(TablaHorarioCita.getValueAt(filaSeleccionada, 0).toString());
            LocalDateTime hora_inicio = LocalDateTime.parse(TablaHorarioCita.getValueAt(filaSeleccionada, 5).toString(), formateador);
            LocalDateTime hora_fin = LocalDateTime.parse(TablaHorarioCita.getValueAt(filaSeleccionada, 6).toString(), formateador);
            
            System.out.println(hora_inicio+"");
            System.out.println(hora_fin+"");
            String motivo = (txtAreaMotivo.getText() != null) ? txtAreaMotivo.getText() : "";
            int idUsuario = 1;
            
            int resultado = controlador.RegistrarCita(idPaciente,idMedico, hora_inicio, hora_fin, motivo,idUsuario);
            
            if (resultado > 0) {
                JOptionPane.showMessageDialog(
                    this,
                    "Registro realizado exitosamente para el médico ID: " + idMedico,
                    "Éxito",
                    JOptionPane.INFORMATION_MESSAGE
                );
                
                LimpiarPaciente();
                LimpiarHorario();
                
                try {
                    //SECCION DE TWILIO
                    CitaDAO citaDAO = new CitaDAO();
                    CitaNotificacion cita = citaDAO.obtenerDatosCitaParaNotificacion(resultado);
                    
                    String telefono = cita.getTelefono();
                    String paciente = cita.getPaciente();
                    String medico = cita.getMedico();
                    String especialidad = cita.getEspecialidad();
                    String fecha = cita.getFecha();
                    String hora = cita.getHora();

                    // Llamada directa
                    TwilioService.enviarMensaje(
                        telefono, 
                        paciente, 
                        medico, 
                        especialidad, 
                        fecha, 
                        hora
                    );

                    JOptionPane.showMessageDialog(this, "Notificación enviada por WhatsApp al paciente.");

                } catch (Exception e) {
                    JOptionPane.showMessageDialog(this, "Error al enviar WhatsApp: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                }
            } else {
                JOptionPane.showMessageDialog(
                    this,
                    "No se pudo registrar la cita",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
                );
            }
        } catch (NullPointerException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "La fila seleccionada contiene celdas vacías.");
        }
    }//GEN-LAST:event_btnRegistarCitaActionPerformed
    
    public String obtenerTextoDelGrupo(ButtonGroup grupo) {
        Enumeration<AbstractButton> botones = grupo.getElements();
        while (botones.hasMoreElements()) {
            AbstractButton boton = botones.nextElement();
            if (boton.isSelected()) {
                return boton.getText();
            }
        }
        return ""; // Ninguno seleccionado
    }
