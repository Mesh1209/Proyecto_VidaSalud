    private void btnGuardarPerfilActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarPerfilActionPerformed
        PerfilDAO perfilDAO = new PerfilDAO();
        ControladorPerfil control = new ControladorPerfil(perfilDAO);
        
        // 3. Capturamos los datos de la interfaz
        String username = txtUsername.getText();
        String password = txtPassword.getText(); // Para JPasswordField
        String confirmarPassword = txtConfirmarContra.getText();
        int idRol = cboRol.getSelectedIndex();
        
        if(password == confirmarPassword){
            resultadoPassword = true;
        }
        
        if(resultado && resultadoPassword){
        // Captura el ID de la especialidad desde un JComboBox (asumiendo que guardas los IDs ahí)
            String nombre = txtNombre.getText();
            String apellido = txtApellido.getText();
            int idEspecialidad = cbxEspecialidad.getSelectedIndex(); 

            String telefono = txtTelefono.getText();
            String email = txtEmail.getText();
            String colegiatura = txtColegiatura.getText();

        // Convertir el texto de la duración a entero de forma segura
            int duracionTurno = 20; 
            try {
                if (!txtDuracion.getText().trim().isEmpty()) {
                    duracionTurno = Integer.parseInt(txtDuracion.getText());
                }
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "La duración debe ser un número válido.");
                return;
            }

            // 4. Ejecutamos la acción a través del controlador
            boolean registrado = control.registrarMedico(
                username, password, nombre, apellido, idEspecialidad, telefono, email, colegiatura, duracionTurno
            );
            if (registrado) {
                JOptionPane.showMessageDialog(this, "Registro exitoso");
                Limpiar();
            }
        }else{
            if(resultadoPassword){
                boolean registrado = control.registrarUsuario(username, password, idRol, true);
                Limpiar();
            }else{
                JOptionPane.showMessageDialog(this, "Contraseña incorrecta");
            }
        }
        
    }//GEN-LAST:event_btnGuardarPerfilActionPerformed

    private void cboRolItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_cboRolItemStateChanged
        // TODO add your handling code here:
        String seleccion = (String) cboRol.getSelectedItem();
        
        List<JTextField> camposControlados = new ArrayList<>();
        camposControlados.add(txtNombre);
        camposControlados.add(txtApellido);
        camposControlados.add(txtTelefono);
        camposControlados.add(txtEmail);
        camposControlados.add(txtColegiatura);
        camposControlados.add(txtDuracion);
        
        for (JTextField campo : camposControlados) {
            if (!"Medico".equals(seleccion)) {
                campo.setEnabled(false);
                cbxEspecialidad.setEnabled(false);
                resultado = false;
            } else{
                campo.setEnabled(true);
                cbxEspecialidad.setEnabled(true);
                resultado = true;
            }
        }
    }//GEN-LAST:event_cboRolItemStateChanged

