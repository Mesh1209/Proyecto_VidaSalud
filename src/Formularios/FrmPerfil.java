    private void cargarComboRoles() {
        // Obtener lista desde la BD
        List<Rol> lista = controladorRol.listarRoles();
        cboModel = new DefaultComboBoxModel();
        // Limpiar ítems previos por seguridad
        cboRol.removeAllItems();
        for (Rol rol : lista) {
            cboModel.addElement(rol.getNombreRol());
        }

        cboRol.setModel(cboModel); //
    }

