    private void TablaMedicamentoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TablaMedicamentoMouseClicked
        // TODO add your handling code here:
        if (evt.getClickCount() == 2) { //cantidad de click
            int fila = TablaMedicamento.getSelectedRow();

            if (fila != -1) {//no importa ponerlos en string ya q igual lo convertimos en guardar o actualizar
                // Obtener datos de la tabla
                String id_medicamento = TablaMedicamento.getValueAt(fila, 0).toString();
                String nombre_comercial = TablaMedicamento.getValueAt(fila, 1).toString();
                String nombre_generico = TablaMedicamento.getValueAt(fila, 2).toString();
                String presentacion = TablaMedicamento.getValueAt(fila, 3).toString();               
                String stock = TablaMedicamento.getValueAt(fila, 4).toString();
                String precio_venta = TablaMedicamento.getValueAt(fila, 5).toString();
                String codigo_medicamento = TablaMedicamento.getValueAt(fila, 6).toString();
                // Colocar en los TextBox (JTextField)
                txtMedicamento.setText(id_medicamento);
                txtNombre_comercial.setText(nombre_comercial);
                txtNombre_generico.setText(nombre_generico);
                txtPresentacion.setText(presentacion);
                txtStock.setText(stock);
                txtPrecio_venta.setText(precio_venta);
                txtCodigo.setText(codigo_medicamento);
                
                txtCodigo.setEditable(false);
            }
        }
    }//GEN-LAST:event_TablaMedicamentoMouseClicked

