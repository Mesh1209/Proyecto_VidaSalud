    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
        try {
            String nombre_comercial = txtNombre_comercial.getText();                      
            String nombre_generico= txtNombre_generico.getText();
            String presentacion= txtPresentacion.getText();
            int stock= Integer.parseInt(txtStock.getText());
            double precio_venta=Double.parseDouble(txtPrecio_venta.getText());
            String codigo_medicamento = txtCodigo.getText();
            
            boolean resultado = controlador.CrearMedicamento(nombre_comercial, nombre_generico, presentacion, stock,precio_venta,codigo_medicamento);
            
            if (resultado) {
                JOptionPane.showMessageDialog(
                    this,
                    "Medicamento realizado exitosamente: ",
                    "Éxito",
                    JOptionPane.INFORMATION_MESSAGE
                );
            } else {
                JOptionPane.showMessageDialog(
                    this,
                    "No se pudo registrar la cita",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
                );
            }
        } catch (NullPointerException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "La fila seleccionada contiene celdas vacías.");
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

