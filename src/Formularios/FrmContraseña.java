    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        int idUsuario = Integer.parseInt(txtUsuario.getText());
        String username = txtNombreUsuario.getText();
        String password_hash = txtContra.getText();
        if (username.isEmpty() || password_hash.isEmpty()) {
            JOptionPane.showMessageDialog(this, 
                "Por favor, complete todos los campos.", 
                "Campos vacíos", 
                JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        if (!password_hash.equals(txtConfirmarContra)) {
            JOptionPane.showMessageDialog(this, 
                "Las contraseñas no coinciden. Inténtelo de nuevo.", 
                "Error de coincidencia", 
                JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        try {

            ControladorLogin.actualizarUsuario(idUsuario, username, password_hash);

            JOptionPane.showMessageDialog(this, 
                "Usuario actualizado correctamente.", 
                "Éxito", 
                JOptionPane.INFORMATION_MESSAGE);

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, 
                "El ID de usuario debe ser un número entero válido.", 
                "Si sale esto es porque se rompio el codigo y F", 
                JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

