    //evento DocumentListener para validar la contraseña
    DocumentListener listenerPassword = new DocumentListener() {
        @Override
        public void insertUpdate(DocumentEvent e) { validarContrasenasEnTiempoReal(); }
        @Override
        public void removeUpdate(DocumentEvent e) { validarContrasenasEnTiempoReal(); }
        @Override
        public void changedUpdate(DocumentEvent e) { validarContrasenasEnTiempoReal(); }
    };
    
    
    //metodo de prueba
    private void validarContrasenasEnTiempoReal() {
        String pass1 = new String(txtContra.getText());
        String pass2 = new String(txtConfirmarContra.getText());

        // Si ambos campos están vacíos, ocultamos o reseteamos el mensaje
        if (pass1.isEmpty() && pass2.isEmpty()) {
            lblMensajePassword.setText("");
            return;
        }

        // Comprobamos si coinciden
        if (pass1.equals(pass2)) {
            lblMensajePassword.setText("✓ Las contraseñas coinciden");
            lblMensajePassword.setForeground(new java.awt.Color(46, 125, 50)); // Verde oscuro
        } else {
            lblMensajePassword.setText("✗ Las contraseñas no coinciden");
            lblMensajePassword.setForeground(new java.awt.Color(198, 40, 40)); // Rojo
        }
    }
    
